CREATE TABLE public.projects (
  id text PRIMARY KEY, position bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  data jsonb NOT NULL CHECK (jsonb_typeof(data) = 'object' AND data->>'id' = id)
);
CREATE TABLE public.campaigns (
  id text PRIMARY KEY, position bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  project_id text NOT NULL REFERENCES public.projects(id),
  data jsonb NOT NULL CHECK (jsonb_typeof(data) = 'object' AND data->>'id' = id AND data->>'projectId' = project_id)
);
ALTER TABLE public.observations ADD COLUMN project_id text REFERENCES public.projects(id);
ALTER TABLE public.observations ADD COLUMN campaign_id text REFERENCES public.campaigns(id);
CREATE INDEX observations_project_idx ON public.observations(project_id);
CREATE INDEX observations_campaign_idx ON public.observations(campaign_id);
CREATE INDEX campaigns_project_idx ON public.campaigns(project_id);
ALTER TABLE public.projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.campaigns ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.projects, public.campaigns FROM anon, authenticated;
