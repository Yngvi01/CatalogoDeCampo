CREATE TABLE public.sampling_sites (
  id text PRIMARY KEY, position bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  project_id text NOT NULL REFERENCES public.projects(id),
  data jsonb NOT NULL CHECK (jsonb_typeof(data) = 'object' AND data->>'id' = id AND data->>'projectId' = project_id)
);
ALTER TABLE public.observations ADD COLUMN sampling_site_id text REFERENCES public.sampling_sites(id);
CREATE INDEX observations_sampling_site_idx ON public.observations(sampling_site_id);
CREATE INDEX sampling_sites_project_idx ON public.sampling_sites(project_id);
ALTER TABLE public.sampling_sites ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.sampling_sites FROM anon, authenticated;
