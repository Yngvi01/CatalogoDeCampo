import { test, expect } from "@playwright/test";
import sharp from "sharp";
test("projeto e campanha: criar, editar, registrar, filtrar e exportar", async ({ page }) => {
  page.setDefaultTimeout(15000);
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await page.goto("/");
  await page.getByLabel("Senha").fill("campo-test-only");
  await page.getByRole("button", { name: "Entrar no catálogo" }).click();
  await page.getByRole("button", { name: "Projetos", exact: true }).click();
  await page.getByRole("button", { name: "Novo projeto", exact: true }).click();
  const dialog = page.getByRole("dialog");
  const name = `Inventário E2E ${Date.now()}`;
  await dialog.getByLabel("Nome", { exact: true }).fill(name);
  await dialog.getByLabel("Município / região").fill("Canela");
  await dialog.getByLabel("Responsável").fill("Igor");
  await dialog.getByLabel("Membros").fill("Igor, Maria");
  await dialog.getByRole("button", { name: "Salvar projeto", exact: true }).click();
  await expect(page.getByRole("heading", { name, exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Editar projeto", exact: true }).click();
  await dialog.getByLabel("Descrição", { exact: true }).fill("Inventário de flora em campo");
  await dialog.getByRole("button", { name: "Salvar projeto", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByText("Inventário de flora em campo", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Nova campanha", exact: true }).click();
  await dialog.getByLabel("Nome", { exact: true }).fill("Primavera 2026");
  await dialog.getByLabel("Equipe").fill("Igor");
  await dialog.getByRole("button", { name: "Salvar campanha", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Primavera 2026" })).toBeVisible();
  await page.getByRole("button", { name: "Editar campanha", exact: true }).click();
  await dialog.getByLabel("Objetivo").fill("Levantamento de flora");
  await dialog.getByRole("button", { name: "Salvar campanha", exact: true }).click();
  await expect(page.getByText("Levantamento de flora", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Registrar na campanha", exact: true }).click();
  await expect(dialog.getByRole("combobox", { name: "Projeto", exact: true })).toHaveValue(/.+/);
  await expect(dialog.getByRole("combobox", { name: "Campanha", exact: true })).toHaveValue(/.+/);
  const image = await sharp({ create: { width: 40, height: 40, channels: 3, background: "#698448" } }).png().toBuffer();
  await dialog.locator("input[type=file][multiple]").setInputFiles({ name: "projeto.png", mimeType: "image/png", buffer: image });
  await dialog.locator("summary").filter({ hasText: "Localização e ambiente" }).click();
  await dialog.getByLabel("Latitude", { exact: true }).fill("-29.3");
  await dialog.getByLabel("Longitude", { exact: true }).fill("-50.8");
  await dialog.getByRole("button", { name: "Identificar fotos", exact: true }).click();
  await dialog.getByRole("button", { name: "Continuar com identificação manual" }).click();
  await dialog.getByRole("checkbox", { name: "Guardar foto 1" }).check();
  await dialog.getByRole("button", { name: "Salvar com 1 foto(s)", exact: true }).click();
  await expect(dialog.getByText(name, { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Editar dados", exact: true }).click();
  await expect(dialog.getByRole("combobox", { name: "Projeto", exact: true })).toHaveValue(/.+/);
  await dialog.getByRole("combobox", { name: "Projeto", exact: true }).selectOption("");
  await dialog.getByRole("button", { name: "Salvar alterações", exact: true }).click();
  await expect(dialog.getByText(name, { exact: true })).toHaveCount(0);
  await dialog.getByRole("button", { name: "Editar dados", exact: true }).click();
  await dialog.getByRole("combobox", { name: "Projeto", exact: true }).selectOption({ label: name });
  await dialog.getByRole("combobox", { name: "Campanha", exact: true }).selectOption({ label: "Primavera 2026" });
  await dialog.getByRole("button", { name: "Salvar alterações", exact: true }).click();
  await expect(dialog.getByText(name, { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Fechar", exact: true }).click();
  await page.getByRole("combobox", { name: "Filtrar campanha", exact: true }).selectOption({ label: "Primavera 2026" });
  const response = await page.request.get(await page.getByRole("link", { name: "Exportar GEOJSON", exact: true }).getAttribute("href") as string);
  expect(response.ok()).toBeTruthy();
  const geo = await response.json();
  expect(geo.features).toHaveLength(1);
  expect(geo.features[0].geometry.coordinates).toEqual([-50.8, -29.3]);
  expect(geo.features[0].properties.project).toBe(name);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  expect(errors).toEqual([]);
});
